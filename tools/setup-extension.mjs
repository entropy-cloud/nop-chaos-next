#!/usr/bin/env node
/**
 * Setup an extension project for nop-chaos development.
 *
 * Distributed inside `dist/sdks/` alongside the SDK tarballs. The script
 * resolves its own location to find the tarballs and version manifest, so
 * the consumer only needs to point at the sdks directory.
 *
 * Usage:
 *   node setup-extension.mjs init [--id <id>] [--name <name>] [--target <dir>]
 *   node setup-extension.mjs add [--target <dir>]
 *
 * Modes:
 *   init  — scaffold a new extension project in the target directory.
 *           ERROR if package.json already exists.
 *   add   — add SDK dependencies to an existing extension project.
 *           ERROR if package.json does not exist.
 *
 * Options:
 *   --target <dir>  Target directory (default: current working directory).
 *
 * The script reads `version-manifest.json` (generated by pack:sdk) to
 * install the exact React / dependency versions used by the host, so the
 * extension is guaranteed to be compatible at runtime.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function parseArgs(argv) {
  const args = argv.slice(2);
  const mode = args[0];

  if (mode !== 'init' && mode !== 'add') {
    console.error(`Usage: node setup-extension.mjs <init|add> [options]`);
    console.error(``);
    console.error(`  init [--id <id>] [--name <name>] [--target <dir>]`);
    console.error(`    scaffold a new extension project`);
    console.error(``);
    console.error(`  add [--target <dir>]`);
    console.error(`    add SDK deps to existing project`);
    process.exit(1);
  }

  const options = { mode, id: 'my-extension', name: 'My Extension', target: process.cwd() };

  for (let i = 1; i < args.length; i++) {
    if (args[i] === '--id' && args[i + 1]) {
      options.id = args[++i];
    } else if (args[i] === '--name' && args[i + 1]) {
      options.name = args[++i];
    } else if (args[i] === '--target' && args[i + 1]) {
      options.target = resolve(args[++i]);
    }
  }

  return options;
}

// ---------------------------------------------------------------------------
// Version manifest
// ---------------------------------------------------------------------------

function readVersionManifest() {
  const manifestPath = resolve(__dirname, 'version-manifest.json');
  if (!existsSync(manifestPath)) {
    console.error(`[setup-extension] version-manifest.json not found at ${manifestPath}`);
    console.error(`Make sure you are running this from the dist/sdks/ directory.`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(manifestPath, 'utf8'));
}

// ---------------------------------------------------------------------------
// SDK tarball resolution
// ---------------------------------------------------------------------------

function resolveSdks(manifest) {
  const sdkDir = __dirname;
  const sdkPackages = manifest.sdkPackages || {};
  const vendoredPackages = manifest.vendoredPackages || {};

  /** @type {Record<string, string>} map: packageName → absolute path of tgz */
  const sdkPaths = {};

  for (const [name, version] of Object.entries(sdkPackages)) {
    const tarball = findTarball(sdkDir, name, version);
    if (tarball) {
      sdkPaths[name] = tarball;
    }
  }

  for (const [name, version] of Object.entries(vendoredPackages)) {
    const tarball = findTarball(sdkDir, name, version);
    if (tarball) {
      sdkPaths[name] = tarball;
    }
  }

  return sdkPaths;
}

function findTarball(sdkDir, packageName, version) {
  // npm pack naming: @nop-chaos/shared → nop-chaos-shared-0.1.0.tgz
  // The scoped prefix becomes: remove @, replace / with -
  const prefix = packageName.startsWith('@')
    ? packageName.slice(1).replace('/', '-')
    : packageName;
  const filename = `${prefix}-${version}.tgz`;
  const fullPath = resolve(sdkDir, filename);
  if (existsSync(fullPath)) {
    return fullPath;
  }
  return null;
}

// ---------------------------------------------------------------------------
// init mode
// ---------------------------------------------------------------------------

async function initProject(options, manifest, sdkPaths) {
  const targetDir = options.target;
  const pkgPath = resolve(targetDir, 'package.json');

  if (existsSync(pkgPath)) {
    console.error(`[setup-extension] init: package.json already exists in ${targetDir}`);
    console.error(`Use 'add' mode to add SDK dependencies to an existing project.`);
    process.exit(1);
  }

  mkdirSync(targetDir, { recursive: true });
  console.log(`[setup-extension] Initializing extension project: ${options.id} in ${targetDir}`);

  // --- package.json ---
  const peerDeps = {};
  const sdkDeps = {};
  const vendoredDeps = {};

  for (const [name, version] of Object.entries(manifest.sdkPackages || {})) {
    const tarballPath = sdkPaths[name];
    if (tarballPath) {
      sdkDeps[name] = `file:${tarballPath}`;
    }
  }

  for (const [name, version] of Object.entries(manifest.vendoredPackages || {})) {
    const tarballPath = sdkPaths[name];
    if (tarballPath) {
      vendoredDeps[name] = `file:${tarballPath}`;
    }
  }

  // Core peer deps from the host's actual versions
  const deps = manifest.dependencies || {};

  const pkg = {
    name: `extension-${options.id}`,
    version: '0.0.1',
    private: true,
    type: 'module',
    scripts: {
      dev: 'vite',
      'dev:standalone': 'vite --config vite.standalone.config.ts',
      build: `tsc -p tsconfig.json --noEmit && node node_modules/@nop-chaos/extension-dev/src/cli.mjs build --root . --id ${options.id} --name "${options.name}" --version 0.0.1 --entry src/index.ts --out dist`,
      preview: 'vite preview',
      typecheck: 'tsc -p tsconfig.json --noEmit',
    },
    dependencies: {
      ...sdkDeps,
      ...vendoredDeps,
      react: deps.react || '^19.0.0',
      'react-dom': deps['react-dom'] || '^19.0.0',
    },
    peerDependencies: {
      '@nop-chaos/shared': '*',
      '@nop-chaos/ui': '*',
      '@nop-chaos/plugin-bridge': '*',
      react: deps.react || '^19.0.0',
      'react-dom': deps['react-dom'] || '^19.0.0',
    },
    devDependencies: {
      '@types/react': '^19.0.0',
      '@types/react-dom': '^19.0.0',
      '@vitejs/plugin-react': '^6.0.1',
      typescript: '^6.0.2',
      vite: '^8.0.3',
    },
  };

  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
  console.log(`  ✓ package.json`);

  // --- tsconfig.json ---
  const tsconfig = {
    compilerOptions: {
      ignoreDeprecations: '6.0',
      target: 'ES2022',
      useDefineForClassFields: true,
      lib: ['ES2022', 'DOM', 'DOM.Iterable'],
      allowJs: false,
      skipLibCheck: true,
      esModuleInterop: true,
      allowSyntheticDefaultImports: true,
      strict: true,
      forceConsistentCasingInFileNames: true,
      module: 'ESNext',
      moduleResolution: 'Bundler',
      types: ['vite/client'],
      resolveJsonModule: true,
      isolatedModules: true,
      noEmit: true,
      jsx: 'react-jsx',
    },
    include: ['src'],
  };

  writeFileSync(resolve(targetDir, 'tsconfig.json'), `${JSON.stringify(tsconfig, null, 2)}\n`);
  console.log(`  ✓ tsconfig.json`);

  // --- vite.config.ts ---
  const viteConfig = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { hostShellPlugin } from './extension-host-shell-plugin.mjs';

// Main dev config: serves the built host (if available) + auto-injects
// this extension's source. Changes to src/** trigger HMR.
//
// HOST_DIST env var points to a built nop-chaos-next dist directory.
// Falls back gracefully to standalone if HOST_DIST is not set.
export default defineConfig({
  base: './',
  resolve: { tsconfigPaths: true },
  plugins: [react(), ...hostShellPlugin({ entry: '/src/index.ts' })],
  server: { cors: true, port: 4180, strictPort: false },
  preview: { port: 4180 },
});
`;

  writeFileSync(resolve(targetDir, 'vite.config.ts'), viteConfig);
  console.log(`  ✓ vite.config.ts`);

  // --- vite.standalone.config.ts (fallback UI preview without host) ---
  const standaloneConfig = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

// Standalone preview: serves only this extension's UI without the host.
// Use when HOST_DIST is not available or you want to iterate on UI in
// isolation.
export default defineConfig({
  root: 'src/standalone',
  base: './',
  resolve: { tsconfigPaths: true },
  plugins: [react()],
  server: { port: 4180, strictPort: false },
});
`;

  writeFileSync(resolve(targetDir, 'vite.standalone.config.ts'), standaloneConfig);
  console.log(`  ✓ vite.standalone.config.ts`);

  // --- extension-host-shell-plugin.mjs (copied from sdks) ---
  const pluginSource = resolve(__dirname, 'extension-host-shell-plugin.mjs');
  if (existsSync(pluginSource)) {
    const { copyFileSync } = await import('node:fs');
    copyFileSync(pluginSource, resolve(targetDir, 'extension-host-shell-plugin.mjs'));
    console.log(`  ✓ extension-host-shell-plugin.mjs`);
  } else {
    console.warn(`  ! extension-host-shell-plugin.mjs not found in ${__dirname}`);
  }

  // --- src/index.ts ---
  mkdirSync(resolve(targetDir, 'src'), { recursive: true });
  const indexTs = `import type { ShellExtension } from '@nop-chaos/shared';

const extension: ShellExtension = {
  id: '${options.id}',
  order: 50,
  branding: {
    name: '${options.name}',
    shortName: '${options.name}',
  },
  builtinPages: [],
  userMenuItems: [],
};

export default extension;
`;

  writeFileSync(resolve(targetDir, 'src/index.ts'), indexTs);
  console.log(`  ✓ src/index.ts`);

  // --- src/standalone/main.tsx ---
  mkdirSync(resolve(targetDir, 'src/standalone'), { recursive: true });
  const mainTsx = `import { createRoot } from 'react-dom/client';

createRoot(document.getElementById('root')!).render(
  <div>
    <h1>${options.name} — Standalone Preview</h1>
    <p>Edit <code>src/index.ts</code> to define your extension.</p>
  </div>,
);
`;

  writeFileSync(resolve(targetDir, 'src/standalone/main.tsx'), mainTsx);
  console.log(`  ✓ src/standalone/main.tsx`);

  // --- src/standalone/index.html ---
  const indexHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${options.name} — Standalone</title>
</head>
<body>
  <div id="root"></div>
  <script type="module" src="./main.tsx"></script>
</body>
</html>
`;

  writeFileSync(resolve(targetDir, 'src/standalone/index.html'), indexHtml);
  console.log(`  ✓ src/standalone/index.html`);

  console.log(``);
  console.log(`[setup-extension] Run 'pnpm install' to install dependencies.`);
}

// ---------------------------------------------------------------------------
// add mode
// ---------------------------------------------------------------------------

function addDeps(options, manifest, sdkPaths) {
  const targetDir = options.target;
  const pkgPath = resolve(targetDir, 'package.json');

  if (!existsSync(pkgPath)) {
    console.error(`[setup-extension] add: no package.json found in ${targetDir}`);
    console.error(`Use 'init' mode to create a new extension project.`);
    process.exit(1);
  }

  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));

  console.log(`[setup-extension] Adding SDK dependencies to ${pkg.name || targetDir}`);

  // Add SDK packages
  for (const [name, version] of Object.entries(manifest.sdkPackages || {})) {
    const tarballPath = sdkPaths[name];
    if (tarballPath) {
      pkg.dependencies = pkg.dependencies || {};
      pkg.dependencies[name] = `file:${tarballPath}`;
      console.log(`  + ${name} → ${tarballPath}`);
    }
  }

  // Add vendored packages (for type-checking)
  for (const [name, version] of Object.entries(manifest.vendoredPackages || {})) {
    const tarballPath = sdkPaths[name];
    if (tarballPath) {
      pkg.dependencies = pkg.dependencies || {};
      pkg.dependencies[name] = `file:${tarballPath}`;
      console.log(`  + ${name} → ${tarballPath}`);
    }
  }

  // Add/update React versions from host
  const deps = manifest.dependencies || {};
  pkg.dependencies = pkg.dependencies || {};
  if (deps.react) {
    pkg.dependencies.react = deps.react;
  }
  if (deps['react-dom']) {
    pkg.dependencies['react-dom'] = deps['react-dom'];
  }

  // Ensure peerDependencies
  pkg.peerDependencies = pkg.peerDependencies || {};
  pkg.peerDependencies['@nop-chaos/shared'] = '*';
  pkg.peerDependencies['@nop-chaos/ui'] = '*';
  pkg.peerDependencies['@nop-chaos/plugin-bridge'] = '*';
  if (deps.react) {
    pkg.peerDependencies.react = deps.react;
  }
  if (deps['react-dom']) {
    pkg.peerDependencies['react-dom'] = deps['react-dom'];
  }

  // Ensure devDependencies
  pkg.devDependencies = pkg.devDependencies || {};
  pkg.devDependencies['@types/react'] = pkg.devDependencies['@types/react'] || '^19.0.0';
  pkg.devDependencies['@types/react-dom'] = pkg.devDependencies['@types/react-dom'] || '^19.0.0';
  pkg.devDependencies['@vitejs/plugin-react'] = pkg.devDependencies['@vitejs/plugin-react'] || '^6.0.1';
  pkg.devDependencies.typescript = pkg.devDependencies.typescript || '^6.0.2';
  pkg.devDependencies.vite = pkg.devDependencies.vite || '^8.0.3';

  // Ensure type module and scripts
  pkg.type = 'module';
  pkg.scripts = pkg.scripts || {};
  if (!pkg.scripts.typecheck) {
    pkg.scripts.typecheck = 'tsc -p tsconfig.json --noEmit';
  }
  if (!pkg.scripts.build) {
    pkg.scripts.build = `tsc -p tsconfig.json --noEmit && node node_modules/@nop-chaos/extension-dev/src/cli.mjs build --root . --id ${pkg.name || 'my-extension'} --name "${pkg.name || 'My Extension'}" --version 0.0.1 --entry src/index.ts --out dist`;
  }

  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
  console.log(``);
  console.log(`[setup-extension] package.json updated. Run 'pnpm install' to install.`);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const options = parseArgs(process.argv);
  const manifest = readVersionManifest();
  const sdkPaths = resolveSdks(manifest);

  console.log(`[setup-extension] SDK directory: ${__dirname}`);
  console.log(`[setup-extension] Host API version: ${manifest.hostApiVersion || 'unknown'}`);
  console.log(``);

  if (options.mode === 'init') {
    await initProject(options, manifest, sdkPaths);
  } else {
    addDeps(options, manifest, sdkPaths);
  }
}

main();
